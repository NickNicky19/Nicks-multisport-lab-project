test('clock validation preserves nanoseconds, separate normalization and source market freshness',()=>{
  assert.equal(nativeOfferClock('2026-10-23T12:01:00.000000001Z')-nativeOfferClock('2026-10-23T12:01:00Z'),1n);
  assert.throws(()=>nativeOfferClock('2026-10-23T12:01Z'));
  assert.equal(nativeOfferClock('2026-10-23T12:01Z',{allowMinuteResolution:true}),nativeOfferClock('2026-10-23T12:01:00Z'));
  for(const value of ['2026-02-30T12:00:00Z','2026-10-23T24:00:00Z','2026-10-23T12:00:00.1234567890Z'])assert.throws(()=>nativeOfferClock(value));
  const later=fixture();later.normalized_at='2026-10-23T12:01:00.000000001Z';seal(later);validateNativeOffer(later,now);
  assert.throws(()=>validateNativeOffer(later,'2026-10-23T12:01:00.000000Z'));
  for(const mutate of [o=>o.normalized_at='2026-10-23T12:00:59.999999999Z',o=>o.price_changed_at='2026-10-23T11:59:59.987654322Z',
    o=>o.market_polled_at='2026-10-23T11:00:00Z',o=>o.knowledge_observed_at='2026-10-23T12:00:00.000000001Z']){
    const o=fixture();mutate(o);seal(o);assert.throws(()=>validateNativeOffer(o,now),String(mutate));
  }
});

