test('typed meaning, hash checking and original-byte authentication remain separate',async()=>{
  const o=fixture();o.price.value='2.5';validateNativeOffer(o,now);await assert.rejects(verifyNativeOfferHash(o,webcrypto,now),/digest mismatch/);
  seal(o);await verifyNativeOfferHash(o,webcrypto,now); // Python original-byte replay rejects this factual change.
  assert.equal(nativeOfferPubliclyAdmitted(o),false);o.evidence_lane='ACTUAL_SOURCE_REPLAY';o.public_admission=true;seal(o);
  assert.equal(nativeOfferPubliclyAdmitted(o),false);assert.equal(nativeOfferPubliclyAdmitted(null),false);
  assert.throws(()=>validateNativeOffer(o,now),/self-granted eligibility/);
});

